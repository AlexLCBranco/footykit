// Writes src/map/basemaps.ts, the outlines of the two continent maps — once, by hand
// (`npx tsx scripts/make-basemaps.ts`); nothing here runs in the app or loads anything at runtime.
// Source (devDependency, no network): world-atlas 2.0.2 `countries-50m.json` (Natural Earth 1:50m, public domain).
// Projection: d3-geo's azimuthal equal-area, centred on each continent and fitted to a MAP_W-wide box around its
// extent (Europe: 11° W – 35° E, 35° – 62° N, so Istanbul and the Nordic grounds are in; South America: 82° – 34° W,
// 56° S – 13° N). The app projects venues with the same parameters (src/map/project.ts).

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoAzimuthalEqualArea, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';
import { presimplify, simplify, sphericalTriangleArea } from 'topojson-simplify';
import type { GeometryCollection, Topology } from 'topojson-specification';
import type { Feature, FeatureCollection, Polygon } from 'geojson';

const require = createRequire(import.meta.url);
const world = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8')) as Topology;
const simple = simplify(presimplify(world as never, sphericalTriangleArea), 1e-6) as Topology;
const countries = (feature(simple, simple.objects.countries as GeometryCollection) as FeatureCollection).features;

const MAP_W = 1000;
const box = (w: number, e: number, s: number, n: number): Feature<Polygon> => {
  // a box along meridians and parallels, densified so the projected outline follows the curves
  const ring: [number, number][] = [];
  for (let x = w; x <= e; x += 1) ring.push([x, s]);
  for (let y = s; y <= n; y += 1) ring.push([e, y]);
  for (let x = e; x >= w; x -= 1) ring.push([x, n]);
  for (let y = n; y >= s; y -= 1) ring.push([w, y]);
  ring.push([w, s]);
  return { type: 'Feature', properties: {}, geometry: { type: 'Polygon', coordinates: [ring.reverse()] } };
};

const round = (d: string | null) => (d ?? '').replace(/-?\d+\.\d+/g, (n) => String(Math.round(+n)));
function make(name: string, center: [number, number], extent: Feature<Polygon>) {
  const p = geoAzimuthalEqualArea().rotate([-center[0], -center[1]]).fitWidth(MAP_W, extent);
  const b = geoPath(p).bounds(extent);
  const h = Math.ceil(b[1][1] - b[0][1]);
  const [tx, ty] = p.translate();
  p.translate([tx - b[0][0], ty - b[0][1]]).clipExtent([[0, 0], [MAP_W, h]]);
  const path = geoPath(p);
  const land = countries.map((f) => round(path(f))).filter((d) => d.length > 0);
  return { name, w: MAP_W, h, rotate: [-center[0], -center[1]] as [number, number], scale: p.scale(), translate: p.translate(), land };
}

const maps = {
  europe: make('Europe', [12, 49], box(-11, 35, 35, 62)),
  southAmerica: make('South America', [-60, -21], box(-82, -34, -56, 13)),
};
const src = `// Generated by scripts/make-basemaps.ts — do not edit by hand. Land: Natural Earth 1:50m via world-atlas 2.0.2
// (public domain). d3-geo azimuthal equal-area, ${MAP_W} units wide; the app projects with the same parameters.

export interface Basemap { name: string; w: number; h: number; rotate: [number, number]; scale: number; translate: [number, number]; land: string[] }

export const BASEMAPS: Record<'europe' | 'southAmerica', Basemap> = ${JSON.stringify(maps)};
`;
writeFileSync('src/map/basemaps.ts', src);
console.log(`src/map/basemaps.ts: Europe ${maps.europe.w}×${maps.europe.h}, South America ${maps.southAmerica.w}×${maps.southAmerica.h}, ${(src.length / 1024).toFixed(0)} KB`);
